export const PI = 3.14159;

// Function 1: Area of a Circle (A = πr²)
export function calculateArea(radius) {
    return PI * (radius * radius);
}

// Function 2: Circumference (C = 2πr)
export function calculateCircumference(radius) {
    return 2 * PI * radius;
}

